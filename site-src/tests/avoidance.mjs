import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{},AbortSignal,URLSearchParams,fetch:null};vm.createContext(context);vm.runInContext(fs.readFileSync('dist/avoidance.js','utf8'),context);
const A=context.window.RouteAvoidance,r={s:0,n:1,w:0,e:1};
assert(A.intersects([.5,-2],[.5,2],r),'Crossing detected even with endpoints outside');
