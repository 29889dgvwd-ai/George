assert(!A.intersects([2,-2],[2,2],r));
assert.equal(A.hits([[.5,-2],[.5,2]],[r]).length,1);
const box=A.envelope([{lat:55,lon:37}],150,'mall');assert(box.n>55.0013&&box.s<54.9987);
let calls=0;
context.fetch=async()=>{calls++;return {ok:true,json:async()=>({elements:[{type:'way',tags:{shop:'mall'},geometry:[{lat:55,lon:37},{lat:55.002,lon:37.002}]}]})}};
const area=await A.load([{lat:55,lng:37}],3,{malls:true},new AbortController().signal);
assert.equal(A.hits([[55.001,36.99],[55.001,37.01]],area.zones).length,1);
assert.equal(calls,1);
context.fetch=async()=>{throw Error('offline')};
await assert.rejects(()=>A.load([{lat:56,lng:38}],3,{malls:true},new AbortController().signal),/Не удалось проверить/);
